  // ─── State ───

  let currentLang = 'es';

  function getStoredLang() {
    try {
      return localStorage.getItem('trackflow_lang') || 'es';
    } catch (e) {
      return 'es';
    }
  }

  function setStoredLang(lang) {
    try {
      localStorage.setItem('trackflow_lang', lang);
    } catch (e) { /* ignore */ }
  }

  // ─── Translation function ───

  function t(key) {
    const dict = LOCALE[currentLang] || LOCALE.es;
    return dict[key] || key;
  }

  // ─── Apply translations to DOM ───

  function applyTranslations() {
    currentLang = getStoredLang();

    // Set HTML lang attribute
    document.documentElement.lang = currentLang;

    // Update language toggle button visual state
    updateLangToggleButton();

    // Translate document title
    const titleKey = document.querySelector('meta[name="i18n-title"]');
    if (titleKey) {
      document.title = t(titleKey.getAttribute('content'));
    }

    // Translate elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = t(key);
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key && el.placeholder !== undefined) {
        el.placeholder = t(key);
      }
    });

    // Translate titles / tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-title');
      if (key) {
        el.title = t(key);
      }
    });
  }

  // ─── Toggle language ───

  function toggleLanguage() {
    currentLang = currentLang === 'es' ? 'en' : 'es';
    setStoredLang(currentLang);
    applyTranslations();
    // Re-run page-specific initializations if available
    if (typeof window.__onLangChange === 'function') {
      window.__onLangChange(currentLang);
    }
  }

  // ─── Update language toggle button visual ───

  function updateLangToggleButton() {
    const btn = document.getElementById('langToggle');
    if (btn) {
      if (currentLang === 'es') {
        btn.innerHTML = '<span class="font-bold">ES</span> <span class="opacity-60">|</span> <span class="opacity-60">EN</span>';
      } else {
        btn.innerHTML = '<span class="opacity-60">ES</span> <span class="opacity-60">|</span> <span class="font-bold">EN</span>';
      }
    }
  }

  // ─── Expose globally ───

  window.__ = t;
  window.__lang = function () { return getStoredLang(); };
  window.__toggleLang = function () {
    toggleLanguage();
  };
  window.__applyTranslations = applyTranslations;

  // ─── Autoload on DOMContentLoaded ───

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyTranslations);
  } else {
    applyTranslations();
  }
